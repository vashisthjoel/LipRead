"""Pydantic data schemas for LipRead FastAPI service.

Defines typed request parameters, response models, and error structures.
All response schemas strictly reflect fields provided by the underlying
InferenceEngine without fabricating metrics or confidence values.
"""

from __future__ import annotations

from typing import Optional
from pydantic import BaseModel, Field


class HealthResponse(BaseModel):
    """Service health and model availability status."""

    status: str = Field(
        default="ok",
        description="Overall service health status ('ok' or 'degraded').",
        examples=["ok"],
    )
    service: str = Field(
        default="LipRead",
        description="Application service identifier.",
        examples=["LipRead"],
    )
    model_loaded: bool = Field(
        description="True if the PyTorch model and InferenceEngine are loaded and ready in memory.",
        examples=[True],
    )
    device: Optional[str] = Field(
        default=None,
        description="Active compute device for inference ('cuda' or 'cpu').",
        examples=["cuda:0"],
    )
    checkpoint: Optional[str] = Field(
        default=None,
        description="Filename or path of the active model checkpoint.",
        examples=["best_model.pt"],
    )
    model_version: Optional[str] = Field(
        default="0.1.0",
        description="Project and model version tag.",
        examples=["0.1.0"],
    )


class PredictionResponse(BaseModel):
    """Transcription response returned after video lip-reading inference."""

    transcription: str = Field(
        description="Final transcription (contextually corrected if applied, otherwise raw CTC output).",
        examples=["bin blue at f two now"],
    )
    raw_transcription: Optional[str] = Field(
        default=None,
        description="Original unedited transcription produced directly by the CTC decoder.",
        examples=["pin blue at f two now"],
    )
    corrected_transcription: Optional[str] = Field(
        default=None,
        description="Contextually corrected transcription generated by the LLM post-processor.",
        examples=["bin blue at f two now"],
    )
    correction_applied: bool = Field(
        default=False,
        description="True if LLM contextual post-processing modified the transcript.",
        examples=[True],
    )
    correction_model: Optional[str] = Field(
        default=None,
        description="LLM provider and model identifier used for contextual post-processing.",
        examples=["openai:gpt-4o-mini"],
    )
    method: str = Field(
        description="Decoding algorithm used ('greedy' or 'beam').",
        examples=["greedy"],
    )
    confidence: Optional[float] = Field(
        default=None,
        description=(
            "Mean max log-probability across frames as computed by InferenceEngine. "
            "Values reside in (-inf, 0]. Null if unavailable."
        ),
        examples=[-0.4521],
    )
    processing_time_seconds: float = Field(
        description="Total wall-clock duration of preprocessing and inference in seconds.",
        examples=[0.385],
    )
    num_frames: int = Field(
        description="Number of video frames processed in the temporal sequence.",
        examples=[75],
    )


class ErrorResponse(BaseModel):
    """Standardized JSON error response."""

    detail: str = Field(
        description="Descriptive explanation of the error.",
        examples=["Unsupported file format. Please upload an MP4, AVI, or MOV video."],
    )
    error_code: Optional[str] = Field(
        default=None,
        description="Machine-readable error classification code.",
        examples=["UNSUPPORTED_MEDIA_TYPE"],
    )
